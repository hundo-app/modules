    #[test]
    fn act_three_moves_the_pilgrims() {
        // Pilgrims leave the Far Fields in Act 3.
        assert!(absent_areas("Pilgrim 01", true).contains(&"Wilds"));
        assert!(absent_areas("Pilgrim 01", false).is_empty());
        // The Pinstress is only met in Act 3.
        assert!(elsewhen("Pinstress Boss", false));
        assert!(!elsewhen("Pinstress Boss", true));
        assert!(absent_areas("Pinstress Boss", false).contains(&"Peak"));
    }

